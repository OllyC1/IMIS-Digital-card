create extension if not exists pgcrypto;

create table public.cards (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  full_name text not null check (char_length(full_name) between 1 and 120),
  job_title text not null check (char_length(job_title) between 1 and 120),
  email text not null check (char_length(email) between 3 and 200),
  office_phone text,
  mobile_phone text,
  office_address text,
  linkedin_url text,
  experience text,
  specialties text[] not null default '{}',
  photo_url text,
  photo_path text,
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index cards_published_slug_idx on public.cards (slug) where published = true;

create table public.admin_login_attempts (
  id bigint generated by default as identity primary key,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);

create index admin_login_attempts_ip_time_idx on public.admin_login_attempts (ip_hash, attempted_at desc);

create function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger cards_set_updated_at
before update on public.cards
for each row execute function public.set_updated_at();

alter table public.cards enable row level security;
alter table public.admin_login_attempts enable row level security;

revoke all on public.cards from anon, authenticated;
revoke all on public.admin_login_attempts from anon, authenticated;
grant select, insert, update, delete on public.cards to service_role;
grant select, insert, update, delete on public.admin_login_attempts to service_role;
grant usage, select on sequence public.admin_login_attempts_id_seq to service_role;

